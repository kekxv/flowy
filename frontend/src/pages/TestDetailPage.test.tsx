it('repaginates A5 preview and keeps print disabled until the preview is ready', async () => {
  let finish!: (value: { pages: number; width: number; height: number }) => void
  vi.mocked(buildReportPreview).mockImplementation(() => new Promise(resolve => { finish = resolve }))
  show()
  fireEvent.click(await screen.findByRole('button', { name: '打印全部报告' }))
  const preview = screen.getByRole('dialog', { name: '打印预览' })
  expect(within(preview).getByRole('button', { name: '确认并打印' })).toBeDisabled()
  await act(async () => { finish({ pages: 2, width: 794, height: 2246 }) })
  fireEvent.change(within(preview).getByLabelText('预览纸张'), { target: { value: 'A5' } })
  await waitFor(() => expect(buildReportPreview).toHaveBeenLastCalledWith(expect.anything(), expect.anything(), 'A5', expect.any(AbortSignal), 'zh'))
  expect(within(preview).getByRole('button', { name: '确认并打印' })).toBeDisabled()
  await act(async () => { finish({ pages: 3, width: 560, height: 2380 }) })
  expect(within(preview).getByRole('button', { name: '确认并打印' })).not.toBeDisabled()
})

